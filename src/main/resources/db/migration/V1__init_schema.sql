CREATE TABLE usuario (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    senha_hash VARCHAR(255) NOT NULL,
    cpf VARCHAR(11),
    perfil VARCHAR(20) NOT NULL,
    posto VARCHAR(100),
    gestor_id INT,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    bloqueado BOOLEAN NOT NULL DEFAULT FALSE,
    criado TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_usuario_gestor FOREIGN KEY (gestor_id) REFERENCES usuario(id)
);

CREATE TABLE tipo_solicitacao (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(250) NOT NULL,
    descricao TEXT,
    requer_aprovacao BOOLEAN NOT NULL DEFAULT FALSE,
    visivel_para_perfil VARCHAR(20),
    visivel_para_posto VARCHAR(100),
    categoria VARCHAR(100),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_por_id INT NOT NULL,
    criado TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_tipo_solic_criador FOREIGN KEY (criado_por_id) REFERENCES usuario(id)
);

CREATE TABLE campo_formulario (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_solicitacao_id INT NOT NULL,
    rotulo VARCHAR(150) NOT NULL,
    tipo_campo VARCHAR(20) NOT NULL,
    obrigatorio BOOLEAN NOT NULL DEFAULT FALSE,
    ordem INT NOT NULL DEFAULT 0,
    opcoes TEXT,
    CONSTRAINT fk_campo_tipo_solic FOREIGN KEY (tipo_solicitacao_id) REFERENCES tipo_solicitacao(id) ON DELETE CASCADE
);

CREATE TABLE ticket (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    colaborador_id INT NOT NULL,
    tipo_solicitacao_id INT NOT NULL,
    status VARCHAR(20) NOT NULL,
    analista_id INT,
    criado TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_ticket_colaborador FOREIGN KEY (colaborador_id) REFERENCES usuario(id),
    CONSTRAINT fk_ticket_tipo_solic FOREIGN KEY (tipo_solicitacao_id) REFERENCES tipo_solicitacao(id),
    CONSTRAINT fk_ticket_analista FOREIGN KEY (analista_id) REFERENCES usuario(id)
);

CREATE TABLE resposta_formulario (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id INT NOT NULL,
    campo_id INT NOT NULL,
    valor_texto TEXT,
    caminho_arquivo VARCHAR(500),
    CONSTRAINT fk_resp_ticket FOREIGN KEY (ticket_id) REFERENCES ticket(id) ON DELETE CASCADE,
    CONSTRAINT fk_resp_campo FOREIGN KEY (campo_id) REFERENCES campo_formulario(id)
);

CREATE TABLE interacao_ticket (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id INT NOT NULL,
    autor_id INT NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    conteudo TEXT NOT NULL,
    status_para VARCHAR(20),
    criado TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_interacao_ticket FOREIGN KEY (ticket_id) REFERENCES ticket(id) ON DELETE CASCADE,
    CONSTRAINT fk_interacao_autor FOREIGN KEY (autor_id) REFERENCES usuario(id)
);

CREATE TABLE aprovacao (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id INT NOT NULL,
    aprovador_id INT NOT NULL,
    decisao VARCHAR(20) NOT NULL,
    comentario TEXT,
    decidido_em TIMESTAMP,
    criado TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_aprovacao_ticket FOREIGN KEY (ticket_id) REFERENCES ticket(id) ON DELETE CASCADE,
    CONSTRAINT fk_aprovacao_aprovador FOREIGN KEY (aprovador_id) REFERENCES usuario(id)
);

CREATE TABLE artigo (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(255) NOT NULL,
    conteudo TEXT NOT NULL,
    categoria VARCHAR(100) NOT NULL,
    publicado BOOLEAN NOT NULL DEFAULT TRUE,
    autor_id INT NOT NULL,
    criado TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_artigo_autor FOREIGN KEY (autor_id) REFERENCES usuario(id)
);
